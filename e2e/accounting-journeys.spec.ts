test('invoice draft survives reload → sales/tax/COGS journals → receipt form → reports', async ({ page }) => {
  const { orgId, vendor, customer, item } = await accountingCompany(page)
  // Arrange real purchased stock, not mocked availability or a cached balance.
  await api(page, '/bills', {
    vendorId: vendor.id, vendorInvoiceNo: 'STOCK-FOR-SALE', issueDate: DATE, status: 'OPEN',
    taxable: false, taxRate: 0, lines: [{ itemId: item.id, description: item.name, quantity: 10, price: 1000, lineTotal: 10000 }],
  }, 'POST')
  await page.goto('/ar/invoices/new')
  await choose(page, 'Search & Select Customer...', customer.name)
  await page.locator('input[name="issueDate"]:visible').fill(DATE)
  await page.locator('input[name="dueDate"]:visible').fill('2026-10-15')
  await page.getByPlaceholder('Type to search items or add custom line...').filter({ visible: true }).fill(item.name)
  await page.getByText(item.name, { exact: true }).click()
  const row = page.getByRole('row').filter({ has: page.getByPlaceholder('Description').filter({ visible: true }) })
  await row.locator('input[type="number"]').nth(0).fill('2')
  await row.locator('input[type="number"]').nth(1).fill('2000')
  await row.locator('input[type="number"]').nth(2).fill('10')
  await page.getByRole('button', { name: 'Logistics & Notes' }).click()
  await page.getByRole('checkbox', { name: 'Apply Tax' }).check()
  await page.getByRole('checkbox', { name: 'Total includes tax' }).uncheck()
  await page.locator('textarea[name="notes"]').fill('Persist these sales details')
  const savedDraft = page.waitForResponse(r => r.url().endsWith('/api/v1/invoices') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  expect((await savedDraft).ok()).toBeTruthy()
  await expect(page.getByRole('button', { name: 'Save draft', exact: true })).toBeHidden()
  const invoice = await db.salesInvoice.findFirstOrThrow({ where: { organizationId: orgId }, include: { lines: true } })
  expect(invoice.status).toBe('DRAFT')
  expect(invoice.customerId).toBe(customer.id)
  expect(invoice.notes).toBe('Persist these sales details')
  expect(invoice.issueDate.toISOString().slice(0, 10)).toBe(DATE)
  expect(invoice.dueDate!.toISOString().slice(0, 10)).toBe('2026-10-15')
  expect([Number(invoice.subtotal), Number(invoice.taxAmount), Number(invoice.totalAmount)]).toEqual([3600, 396, 3996])
  expect(invoice.lines).toHaveLength(1)
  expect(invoice.lines[0].itemId).toBe(item.id)
  expect([Number(invoice.lines[0].quantity), Number(invoice.lines[0].price), Number(invoice.lines[0].discountPct)])
    .toEqual([2, 2000, 10])
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(1) // Only the stock bill.

  await page.goto(`/ar/invoices/edit?invoiceId=${invoice.id}`)
  await page.reload()
  await expect(page.locator('input[name="issueDate"]:visible')).toHaveValue(DATE)
  await expect(page.locator('input[name="dueDate"]:visible')).toHaveValue('2026-10-15')
  await expect(page.getByPlaceholder('Description').filter({ visible: true })).toHaveValue(item.name)
  await expect(row.locator('input[type="number"]').nth(0)).toHaveValue('2')
  await expect(row.locator('input[type="number"]').nth(1)).toHaveValue('2000')
  await expect(row.locator('input[type="number"]').nth(2)).toHaveValue('10')
  await page.getByRole('button', { name: 'Logistics & Notes' }).click()
  await expect(page.getByRole('checkbox', { name: 'Apply Tax' })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Total includes tax' })).not.toBeChecked()
  await expect(page.locator('textarea[name="notes"]:visible')).toHaveValue('Persist these sales details')
  const approvedInvoice = page.waitForResponse(r => r.url().endsWith(`/api/v1/invoices/${invoice.id}`) && r.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Save & Approve', exact: true }).click()
  const approvedResponse = await approvedInvoice
  expect(approvedResponse.ok(), await approvedResponse.text()).toBeTruthy()
  const postedLines = await db.salesInvoiceLine.findMany({ where: { invoiceId: invoice.id } })
  expect(postedLines).toHaveLength(1)
  expect(postedLines[0].itemId).toBe(item.id)
  await expect(page.getByRole('button', { name: 'Save & Approve', exact: true })).toBeHidden()
  const entries = await db.journalEntry.findMany({ where: { organizationId: orgId, memo: { contains: invoice.number } } })
  expect(entries).toHaveLength(2)
  const sale = entries.find(e => e.memo?.startsWith('Sales recognition:'))!
  const cogs = entries.find(e => e.id !== sale.id)!
  await expectJournal(orgId, sale.id, [['1-1200', 3996, 0], ['4-1000', 0, 3600], ['2-1100', 0, 396]])
  await expectJournal(orgId, cogs.id, [['5-1000', 2000, 0], ['1-1300', 0, 2000]])
  // A repeated status request cannot post the invoice or consume stock again.
  await api(page, `/invoices/${invoice.id}`, { status: 'SENT' }, 'PUT')
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(3)
  const movements = await db.inventoryLedgerEntry.findMany({ where: { organizationId: orgId, itemId: item.id } })
  expect(movements.reduce((s, l) => s + Number(l.qtyIn) - Number(l.qtyOut), 0)).toBe(8)
  expect(movements.reduce((s, l) => s + Number(l.valueChange), 0)).toBe(8000)

  // The current AR payment table identifies its rows by invoice ID.
  await payThroughForm(page, 'ar', customer.name, invoice.id)
  const receipt = await db.aRPayment.findFirstOrThrow({ where: { organizationId: orgId }, include: { allocations: true } })
  expect(receipt.status).toBe('COMPLETED')
  expect(receipt.allocations).toHaveLength(1)
  expect(receipt.allocations[0].invoiceId).toBe(invoice.id)
  expect(Number(receipt.allocations[0].amountApplied)).toBe(3996)
  await expectJournal(orgId, receipt.journalEntryId!, [['1-1000', 3996, 0], ['1-1200', 0, 3996]])
  expect((await db.salesInvoice.findUniqueOrThrow({ where: { id: invoice.id } })).status).toBe('PAID')
  await expectTrialBalance(page, [['1-1000', 3996, 0], ['1-1200', 0, 0], ['1-1300', 8000, 0], ['2-1000', 0, 10000], ['2-1100', 0, 396], ['4-1000', 0, 3600], ['5-1000', 2000, 0]])
  const pl = await api(page, `/reports/gl?type=profit-loss&dateFrom=${DATE}&dateTo=${DATE}`)
  expect(pl.summary).toMatchObject({ totalRevenue: 3600, totalExpense: 2000, netIncome: 1600 })
  const bs = await api(page, `/reports/gl?type=balance-sheet&asOfDate=${DATE}`)
  expect(bs.summary).toMatchObject({ totalAssets: 11996, totalLiabilities: 10396, currentEarnings: 1600, totalLiabilitiesAndEquity: 11996 })
})

