test('PO form → goods-receipt API → bill form → payment; GR/IR clears without duplicate stock', async ({ page }) => {
  const { orgId, vendor, item } = await accountingCompany(page)
  await page.goto('/ap/pos/new')
  await choose(page, 'Search & select vendor…', vendor.name)
  await page.getByLabel('PO numbering').selectOption('manual')
  await page.getByPlaceholder('e.g. PO-TC-0001').filter({ visible: true }).fill('PO-JOURNEY')
  await page.locator('main input[type="date"]').first().fill(DATE)
  await page.getByPlaceholder('Search SKU or name to add…').filter({ visible: true }).fill(item.name)
  await page.getByText(item.name, { exact: true }).click()
  const row = page.getByRole('row').filter({ has: page.getByPlaceholder('Description').filter({ visible: true }) })
  await row.locator('input[type="number"]').nth(0).fill('3')
  await row.locator('input[type="number"]').nth(1).fill('1000')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/ap/pos')
  const po = await db.purchaseOrder.findFirstOrThrow({ where: { organizationId: orgId }, include: { lines: true } })
  expect(po.number).toBe('PO-JOURNEY')
  expect(po.vendorId).toBe(vendor.id)
  expect(po.status).toBe('DRAFT')
  expect(po.lines).toHaveLength(1)
  expect(po.lines[0].itemId).toBe(item.id)
  expect([Number(po.lines[0].quantity), Number(po.lines[0].price), Number(po.lines[0].receivedQty)]).toEqual([3, 1000, 0])
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(0)
  await api(page, `/purchase-orders/${po.id}`, { status: 'APPROVED' }, 'PUT')
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(0)
  const received = await api(page, `/purchase-orders/${po.id}/receive`, {
    lines: [{ purchaseOrderLineId: po.lines[0].id, qtyReceived: 3 }],
  }, 'POST')
  const receiptEntry = await db.journalEntry.findFirstOrThrow({ where: { organizationId: orgId } })
  await expectJournal(orgId, receiptEntry.id, [['1-1300', 3000, 0], ['2150', 0, 3000]])
  expect(Number((await db.purchaseOrderLine.findUniqueOrThrow({ where: { id: po.lines[0].id } })).receivedQty)).toBe(3)
  expect((await db.purchaseOrder.findUniqueOrThrow({ where: { id: po.id } })).status).toBe('CLOSED')

  await page.goto(`/ap/bills/new?billId=${received.billId}`)
  await expect(page.getByPlaceholder('Description').filter({ visible: true })).toHaveValue(item.name)
  await page.getByPlaceholder('e.g. INV/DE/8842').filter({ visible: true }).fill('PO-SUPPLIER-INVOICE')
  await page.getByRole('button', { name: 'Save & schedule payment', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/ap/bills')
  const bill = await db.bill.findUniqueOrThrow({ where: { id: received.billId }, include: { lines: true } })
  await expectJournal(orgId, bill.journalEntryId!, [['2150', 3000, 0], ['2-1000', 0, 3000]])
  expect(Number((await db.purchaseOrderLine.findUniqueOrThrow({ where: { id: po.lines[0].id } })).receivedQty)).toBe(3)
  const stock = await db.inventoryLedgerEntry.findMany({ where: { organizationId: orgId, itemId: item.id } })
  expect(stock).toHaveLength(1)
  expect([Number(stock[0].qtyIn), Number(stock[0].valueChange)]).toEqual([3, 3000])
  await payThroughForm(page, 'ap', vendor.name, bill.number, bill.issueDate.toISOString().slice(0, 10))
  const payment = await db.aPPayment.findFirstOrThrow({ where: { organizationId: orgId } })
  await expectJournal(orgId, payment.journalEntryId!, [['2-1000', 3000, 0], ['1-1000', 0, 3000]])
  expect((await db.bill.findUniqueOrThrow({ where: { id: bill.id } })).status).toBe('PAID')
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(3)
  const report = await api(page, `/reports/gl?type=trial-balance&asOfDate=${bill.issueDate.toISOString().slice(0, 10)}`)
  expect(report.rows.map((r: { accountCode: string; endingDebit: number; endingCredit: number }) =>
    [r.accountCode, r.endingDebit, r.endingCredit])).toEqual([
      ['1-1000', 0, 3000], ['1-1300', 3000, 0], ['2-1000', 0, 0], ['2150', 0, 0],
    ])
})

test('expense bill retry and reload preserve accounts, tax, withholding and charges', async ({ page }) => {
  const { orgId, vendor } = await accountingCompany(page)
  const expense = await db.account.findFirstOrThrow({ where: { organizationId: orgId, code: '5-1100' } })
  const freight = await db.account.findFirstOrThrow({ where: { organizationId: orgId, code: '5-1000' } })
  await page.goto('/ap/bills/new')
  await choose(page, 'Search & select vendor…', vendor.name)
  await page.getByPlaceholder('e.g. INV/DE/8842').filter({ visible: true }).fill('EXPENSE-JOURNEY')
  await page.locator('main input[type="date"]').first().fill(DATE)
  await page.getByPlaceholder('Search SKU or name to add…').filter({ visible: true }).fill('Journey expense')
  await page.getByText('Add “Journey expense” as a custom line').click()
  const row = page.getByRole('row').filter({ has: page.getByPlaceholder('Description').filter({ visible: true }) })
  await row.locator('select').selectOption(expense.id)
  await row.locator('input[type="number"]').nth(0).fill('2')
  await row.locator('input[type="number"]').nth(1).fill('5000')
  await row.locator('input[type="number"]').nth(2).fill('10')
  await page.getByRole('button', { name: 'Additional costs', exact: true }).click()
  await page.getByRole('button', { name: 'Add cost' }).click()
  const chargeRow = page.getByRole('row').filter({ has: page.getByPlaceholder('e.g. Delivery / freight').filter({ visible: true }) })
  await page.getByPlaceholder('e.g. Delivery / freight').filter({ visible: true }).fill('Delivery')
  await chargeRow.locator('select').selectOption(freight.id)
  await chargeRow.locator('input[type="number"]').nth(0).fill('11')
  await chargeRow.locator('input[type="number"]').nth(1).fill('1000')
  await page.getByRole('button', { name: 'Additional info', exact: true }).click()
  await page.getByRole('checkbox', { name: 'With PPN 11%' }).check()
  await page.locator('select').filter({ has: page.locator('option', { hasText: 'No withholding' }) }).selectOption('2')
  await page.getByPlaceholder('Optional notes / PO reference…').filter({ visible: true }).fill('Expense persistence check')

  // Interrupt only the first submission; retry goes to the real server.
  await page.route('**/api/v1/bills', async route => {
    if (route.request().method() === 'POST') {
      await route.abort('failed')
    } else await route.continue()
  })
  // Dismiss while the click is in flight: Playwright waits for an open dialog
  // before resolving click(), so handling it afterwards deadlocks the test.
  const failed = page.waitForEvent('dialog').then(async dialog => {
    expect(dialog.message()).toContain('Failed to save bill')
    await dialog.dismiss()
  })
  await Promise.all([
    failed,
    page.getByRole('button', { name: 'Save draft', exact: true }).click(),
  ])
  await page.unroute('**/api/v1/bills')
  expect(await db.bill.count({ where: { organizationId: orgId } })).toBe(0)
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(0)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/ap/bills')
  const bill = await db.bill.findFirstOrThrow({ where: { organizationId: orgId }, include: { lines: true, charges: true } })
  expect(bill.status).toBe('DRAFT')
  expect(bill.notes).toBe('Expense persistence check')
  expect([Number(bill.subtotal), Number(bill.taxAmount), Number(bill.withholdingAmount), Number(bill.totalAmount)])
    .toEqual([9000, 1100, 180, 10920])
  expect(bill.lines).toHaveLength(1)
  expect(bill.lines[0].accountId).toBe(expense.id)
  expect(bill.charges).toHaveLength(1)
  expect(bill.charges[0].accountId).toBe(freight.id)
  expect(Number(bill.charges[0].amount)).toBe(1000)
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(0)

  await page.goto(`/ap/bills/new?billId=${bill.id}`)
  await page.reload()
  await expect(page.getByPlaceholder('e.g. INV/DE/8842').filter({ visible: true })).toHaveValue('EXPENSE-JOURNEY')
  await expect(row.locator('select')).toHaveValue(expense.id)
  await expect(row.locator('input[type="number"]').nth(0)).toHaveValue('2')
  await expect(row.locator('input[type="number"]').nth(1)).toHaveValue('5000')
  await expect(row.locator('input[type="number"]').nth(2)).toHaveValue('10')
  await expect(page.getByPlaceholder('Optional notes / PO reference…').filter({ visible: true })).toHaveValue('Expense persistence check')
  await page.getByRole('button', { name: 'Additional costs', exact: true }).click()
  await expect(chargeRow.locator('select')).toHaveValue(freight.id)
  await expect(chargeRow.locator('input[type="number"]').nth(1)).toHaveValue('1000')
  await page.getByRole('button', { name: 'Additional info', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'With PPN 11%' })).toBeChecked()
  await expect(page.locator('select').filter({ has: page.locator('option', { hasText: 'No withholding' }) })).toHaveValue('2')
  await page.getByRole('button', { name: 'Save & schedule payment', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/ap/bills')
  const posted = await db.bill.findUniqueOrThrow({ where: { id: bill.id } })
  await expectJournal(orgId, posted.journalEntryId!, [
    ['5-1100', 9000, 0], ['5-1000', 1000, 0], ['1-1400', 1100, 0], ['2160', 0, 180], ['2-1000', 0, 10920],
  ])
  expect(await db.bill.count({ where: { organizationId: orgId } })).toBe(1)
  expect(await db.inventoryLedgerEntry.count({ where: { organizationId: orgId } })).toBe(0)
  const pl = await api(page, `/reports/gl?type=profit-loss&dateFrom=${DATE}&dateTo=${DATE}`)
  expect(pl.summary).toMatchObject({ totalRevenue: 0, totalExpense: 10000, netIncome: -10000 })

  // Duplicate supplier invoice is rejected atomically, without an extra bill,
  // journal, or stock movement. A different reference can then be saved.
  const orgHeader = { 'x-active-org': orgId }
  const payload = { vendorId: vendor.id, vendorInvoiceNo: 'EXPENSE-JOURNEY', issueDate: DATE, status: 'OPEN',
    lines: [{ description: 'Duplicate expense', accountId: expense.id, quantity: 1, price: 500, lineTotal: 500 }] }
  const duplicate = await page.request.post('http://localhost:3100/api/v1/bills', { headers: orgHeader, data: payload })
  expect(duplicate.status()).toBe(409)
  expect(await db.bill.count({ where: { organizationId: orgId } })).toBe(1)
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(1)
  await api(page, '/bills', { ...payload, vendorInvoiceNo: 'CORRECTED-REFERENCE' }, 'POST')
  expect(await db.bill.count({ where: { organizationId: orgId } })).toBe(2)
  expect(await db.journalEntry.count({ where: { organizationId: orgId } })).toBe(2)
})

